/*==============================================================================
 * M5 · PWM 风扇调速（TIM3 CH1 = PA6，1 kHz）
 *
 * PWM 一句话：用"快速开关"模拟"中间电压"。
 *   1 kHz 下开 30% 时间、关 70% 时间 → 电机/风扇感受到的平均功率就是 30%。
 *   ⭐ 为什么不用 DAC 调压：开关管要么全开（压降≈0）要么全关（无电流），
 *      都不发热；线性调压是把多余电压变成热量，电机场景会烫得没法用。
 *
 * 三个寄存器（改转速只动 CCR，另两个动了频率就变）：
 *   PSC = 83  → 计数时钟 84MHz/84 = 1 MHz   （⚠️ F4 上 APB1 分频≠1 时定时
 *                                             器时钟 = PCLK1×2 = 84MHz，不是 42MHz）
 *   ARR = 999 → PWM 频率 = 1MHz/1000 = 1 kHz
 *   CCR = 占空比，运行时改（HAL：__HAL_TIM_SET_COMPARE）
 *============================================================================*/

#ifndef __M5_FAN_H
#define __M5_FAN_H

#include <stdint.h>

/* 温度曲线（温度单位是 ×10，280 = 28.0℃） */
#define FAN_T_START      260     /* 26.0℃ 开始转 */
#define FAN_T_FULL       340     /* 34.0℃ 全速   */
#define FAN_T_HYST       20      /* ⭐ 滞回 2.0℃：转着要降到 24.0℃ 才停 */
#define FAN_T_CUTOFF     300     /* 30.0℃ 触发保护：切断继电器 */

#define FAN_DUTY_MIN     25u     /* 最低 25%（低于此值风扇启动不了，会"咯咯"响） */
#define FAN_DUTY_MAX     100u

/*==============================================================================
 * ⚠️ M5-g 验收专用测试钩子 —— 【验收完必须改回 0】
 *
 * =1 时：m5_fan.c 内部会伪造数据池温度，每 5 s 换一档自动扫完整条曲线，
 *        串口直接看 duty 随温度怎么走（不需要真风扇、不需要温度传感器）。
 * =0 时：走真实采集（温度来自 Modbus / M2）。
 *
 * ⚠️ 忘记改回 0 的后果：温度永远是被注入的假值，
 *    超温保护会周期性"切断继电器"，真机上电会误动作。
 *============================================================================*/
#define M5_FAN_TEST_INJECT   0u

/*==============================================================================
 * API
 *============================================================================*/

/* 启动 PWM 输出。
   ⭐ 必须调：CubeMX 只生成 MX_TIM3_Init()，【不会】帮你 HAL_TIM_PWM_Start()
      （和 HAL_CAN_Start / HAL_ETH_Start_IT 是同一类坑：生成了配置不等于开始工作） */
void M5_FanInit(void);

/* 由 monitor 任务每 1 s 调一次：温度 → 占空比（含滞回 + 超温保护） */
void M5_FanUpdate(void);

/* 当前占空比百分比（0~100） */
uint8_t M5_FanDuty(void);

/* ⭐ 当前是否【真的在转】= duty > 0（BUG-064）
   ⚠️ 状态上报只能用这个，不要用任何"滞回记忆位"：
      在 24.0~26.0℃ 回差区间内，滞回位仍为 1 但 PWM 实际已停输出，
      用它上报会误报"运行中"。 */
uint8_t M5_FanRunning(void);

/* 是否处于超温保护状态（1 = 已切断继电器） */
uint8_t M5_FanCutoff(void);

#endif /* __M5_FAN_H */
