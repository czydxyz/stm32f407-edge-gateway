/*==============================================================================
 * M6 · 掉电补传缓存（W25Q128，SPI1 + PB14 片选）
 *
 * ⭐ 它解决的是"链路全断时数据去哪了"这最后一个洞：
 *     M5 的 DEGRADED 状态只做了一件事 —— `s_lost_cnt++` 记一笔丢失。
 *     工业现场这是不可接受的：温度/告警在断网那 20 分钟里照样在产生，
 *     运维恢复链路后想知道"断网期间发生过什么"，而不是看到一个丢包数。
 *
 * ⭐ 为什么必须存到【外部 SPI Flash】而不是内部 Flash：
 *     ① 内部 Flash 擦写寿命 1 万次，环形缓存每小时写几十次，很快写穿
 *     ② 内部 Flash 擦除要【停 CPU】（取指被 stall），会影响实时性
 *     ③ W25Q128 有 10 万次擦写 + 16 MB 容量，专门干这个活
 *     ⚠️ 但本项目【没有掉电保护】—— 断电瞬间正在写的那一条会损坏，
 *        所以每条带 CRC32，读出来校验不过就当它不存在（见 m6_store.c 说明）。
 *
 * ⭐ 条目为什么是【精简数据】而不是"整个上报帧"：
 *     上报帧 40+ 字节且含协议头/CRC，缓存它没有意义（恢复后要重新组帧），
 *     而且 4 KB 扇区里塞不下几条。真正要保证不丢的是【采集值本身】，
 *     所以条目 = 温湿度 + DI + 继电器 + seq + 时间戳，固定 32 字节。
 *     恢复后按条目内容重新组帧上报，seq 用原来的 → 上位机去重逻辑照样成立。
 *
 * 硬件（正点原子探索者板载 25Q128）：
 *     SPI1_SCK  = PB3
 *     SPI1_MISO = PB4
 *     SPI1_MOSI = PB5
 *     F_CS      = PB14   ← 原理图确认，不要自选
 *     ⚠️ PB3/4/5 是 JTAG 脚，必须在 CubeMX 里把 Debug 设成 SWD 才释放为 GPIO
 *============================================================================*/

#ifndef __M6_STORE_H
#define __M6_STORE_H

#include <stdint.h>

/*==============================================================================
 * 容量与布局
 *============================================================================*/
/* 条目固定 32 字节（内部有 4 字节 CRC32 + 若干头，见 .c 里的 slot_t） */
#define M6_SLOT_SIZE       32u

/* 缓存区占用 W25Q128 的前 2 个扇区（4 KB × 2 = 8 KB → 256 条）
   ⚠️ W25Q128 擦除最小单位是 4 KB 扇区，所以缓存区必须整扇区对齐 */
#define M6_STORE_ADDR      0x00000000u
#define M6_STORE_SECTORS   2u
#define M6_SLOT_MAX        ((M6_STORE_SECTORS * 4096u) / M6_SLOT_SIZE)   /* 256 */

/*==============================================================================
 * 条目内容（精简上报数据，不是完整帧）
 *============================================================================*/
typedef struct {
    uint32_t  seq;            /* ⭐ 原上报的全局序号 —— 补传时沿用，去重才成立 */
    uint32_t  uptime_s;       /* 采集时刻（设备运行秒数） */
    int16_t   temperature;    /* ×10，253 = 25.3℃ */
    int16_t   humidity;       /* ×10 */
    uint8_t   di_status;
    uint8_t   relay_status;
} m6_item_t;

/*==============================================================================
 * API
 *============================================================================*/

/* 初始化：拉高 CS、读 JEDEC ID 自检。
   ⚠️ 失败不会卡死，只是缓存功能不可用（降级为"只计数"，即 M5 行为） */
int  M6_StoreInit(void);

/* 1 = 可用（Flash 在且自检通过），0 = 不可用 */
int  M6_StoreReady(void);

/* 缓存一条。缓存区满时【覆盖最旧的一条】并累计 s_dropped。
   返回 0 = 成功；<0 = 失败 */
int  M6_StorePush(const m6_item_t *item);

/* 取【最旧】的一条（补传用）。返回 0 = 取到；<0 = 缓存空 */
int  M6_StorePeek(m6_item_t *out);

/* 删掉最旧的一条（补传【成功】后才调，失败不要调，否则数据真丢了） */
int  M6_StorePop(void);

/* 当前缓存条数 / 因满被覆盖的条数（后者要如实写进简历，别只报成功数） */
uint16_t M6_StoreCount(void);
uint32_t M6_StoreDropped(void);

/* 诊断：自检用的 Flash JEDEC ID（W25Q128 = 0x00EF4018） */
uint32_t M6_StoreJedecId(void);

#endif /* __M6_STORE_H */
