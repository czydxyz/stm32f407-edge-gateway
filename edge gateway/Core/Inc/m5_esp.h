/*==============================================================================
 * M5 · ESP8266 备份链路驱动（USART3 PB10/PB11，AT 指令）
 *
 * ⚠️ 硬件前提（不满足就别怀疑代码）：
 *   ① P2 跳线帽必须跳到【ATK-MODULE】侧（PB10/PB11 也复用 RS232，跳错就通不了）
 *   ② ESP8266 发射瞬间电流尖峰可达 200 mA+，供电不足会"一连 WiFi 就重启"
 *      —— 十有八九是电源问题，不是 AT 指令问题。建议 VCC 并 100µF + 0.1µF。
 *   ③ 模块出厂一般是 AT 固件，先用串口助手确认 "AT" 回 "OK"
 *
 * ⚠️ 为什么 AT 交互必须做成状态机 + 超时：
 *    ❌ send("AT+CWJAP=..."); vTaskDelay(5000);   // 靠猜时间等结果
 *       → 快了收不全，慢了白等，还把任务卡死 5 秒
 *    ✅ 每次只推进一步，靠"收到完整应答"推进，且【必须有超时分支】
 *       模块不回应的情况太常见（模块死机/断网/电源抖），
 *       没有超时，状态机会永久卡在某个 WAIT 上 —— 这时任务没崩但不再干活，
 *       只能靠存活位发现它"假活"。
 *============================================================================*/

#ifndef __M5_ESP_H
#define __M5_ESP_H

#include <stdint.h>

/*==============================================================================
 * ⚠️ 改成你自己的 WiFi 与上位机地址
 * WiFi：czy123 / czy321321（2.4 GHz —— ESP8266 只支持 2.4G，5G 频段搜不到是正常的）
 *============================================================================*/
#define M5_ESP_SSID        "czy123"
#define M5_ESP_PASS        "czy321321"
#define M5_ESP_PC_IP       "192.168.1.10"
#define M5_ESP_PC_PORT     5002      /* 备份链路用 5002（主链路是 5001） */

/* ⚠️ 端口的字符串形式：AT 命令是字符串拼接出来的，不走 printf 格式化。
   如果写成 "...,%d\r\n" 而没给参数，%d 会【原样发出去】，
   模块收到 "AT+CIPSTART=\"TCP\",\"192.168.1.10\",%d" 必然报错。
   改端口时两处都要改（数字给 C 代码用，字符串给 AT 命令用）。 */
#define M5_ESP_PC_PORT_STR "5002"

/* DMA 循环接收缓冲（USART3 115200，一帧 AT 应答通常几十字节，512 足够） */
#define M5_ESP_RXBUF       512u

/* 应答缓冲（线性，用于关键字匹配） */
#define M5_ESP_RESPBUF     256u

/*==============================================================================
 * API
 *============================================================================*/
void M5_EspInit(void);

/* 每 200 ms 由 m5_link 的 tick 驱动一次 */
void M5_EspTick(uint32_t period_ms);

/* 已连上 TCP 且可发数据 */
int  M5_EspIsUp(void);

/* 发一包数据。0 = 成功。⚠️ 内部会阻塞等 ">" 与 "SEND OK"（有超时，不会死等） */
int  M5_EspSend(const uint8_t *data, uint16_t len);

/* 断开 TCP 连接（切回主链路时调用，释放模块侧资源） */
void M5_EspDisconnect(void);

/* 由 USART3_IRQHandler 在 IDLE 中断时调用（DMA+IDLE 分帧，复用 M2 的思路） */
void M5_EspIdleCallback(void);

/* 由 USART3_IRQHandler 调用 */
void M5_EspIrqHandler(void);

#endif /* __M5_ESP_H */
