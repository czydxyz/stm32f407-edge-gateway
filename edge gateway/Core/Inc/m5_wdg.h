/*==============================================================================
 * M5 · 看门狗裁决（IWDG + WWDG 双狗）
 *
 * ⭐ 一句话：IWDG 管"有没有喂"，WWDG 管"喂的节奏对不对"。
 *
 *   IWDG（独立看门狗，LSI ~32kHz，本工程配 4 s 标称）
 *     防"程序彻底不跑了"：死循环、跑飞、中断被关死
 *     喂狗规则：超时前喂任意一次即可
 *     ⚠️ LSI 实测可能 17~47 kHz，标称 4 s 最快只有 2.72 s → 喂狗周期 1 s 才安全
 *
 *   WWDG（窗口看门狗，PCLK1 分频，本工程窗口 36.7~49.9 ms）
 *     防"程序跑飞后刚好还在周期性喂狗"（假活）
 *     喂狗规则：必须踩在窗口内，喂早了喂晚了都复位
 *     ⚠️ F4 上最长只有 ~50 ms，不可能让 1 s 周期的任务去喂
 *        → 唯一可行用法：用 EWI（早期唤醒中断）在 counter==0x40 时由硬件节拍喂
 *
 * ⭐ 喂狗点唯一性：全工程只允许 M5_WdgKick() 里有一处 HAL_IWDG_Refresh()。
 *    多一处，整套裁决就失效（那个任务只要活着就喂，等于没监控）。
 *============================================================================*/

#ifndef __M5_WDG_H
#define __M5_WDG_H

#include <stdint.h>
#include "m4_task.h"    /* M4_ALIVE_* 存活位定义 */

/*==============================================================================
 * ⚠️ WWDG 总开关（默认 0 = 关闭）——关闭不是偷懒，是工程取舍，理由必须写清楚：
 *
 *   WWDG 的窗口只有 ~50 ms（F4 硬上限，见 M5 文档第 4 步）。
 *   而【内部 Flash 擦除期间 CPU 是完全停摆的】：
 *       F4 参考手册 PM0081：擦除/编程进行中，任何对 Flash 的读访问都会 stall，
 *       直到操作结束。CPU 取指本身就是读 Flash → 整个 CPU 停摆数百毫秒。
 *   于是在 OTA 擦 Bank B（4 个 128 KB 扇区）时：
 *       CPU 停摆 > 50 ms → EWI 中断根本进不来 → WWDG 必然复位
 *       → OTA 永远做不完，而且复位后 Flash 处于"擦了一半"的状态。
 *
 *   IWDG 不受影响（超时 2.72 s > 单扇区擦除时间），所以擦除期间靠
 *   M5_WdgHold() + 扇区间喂狗即可 —— 那是可行的。
 *
 *   所以本工程：
 *     M5_WWDG_ENABLE = 0（默认）：正常运行 + OTA 全功能，靠 IWDG 兜底
 *     M5_WWDG_ENABLE = 1        ：专项验证 WWDG（此时不要做 OTA）
 *============================================================================*/
#ifndef M5_WWDG_ENABLE
#define M5_WWDG_ENABLE   0
#endif

/*==============================================================================
 * 必须报到的任务位掩码
 *
 * ⚠️ 这里【故意不含 MODBUS】：M2 的 Modbus 主站任务目前被注释掉没启用，
 *    如果要求它报到，系统会在宽限期结束后拒喂 → 每 4 秒复位一次，永远起不来。
 *    ⭐ 等 M2 接线完成、把 freertos.c 里的 M2_MasterStart() 放开时，
 *       必须同步把下面这行改成 M4_ALIVE_ALL，否则 Modbus 任务死了没人知道。
 *============================================================================*/
#define M5_ALIVE_REQUIRED   (M4_ALIVE_NET | M4_ALIVE_CAN | M4_ALIVE_LOG)

/* 启动宽限：上电后这段时间内"缺位也照喂"（各任务还在陆续起来） */
#define M5_GRACE_KICKS      10u     /* 10 次 × 1 s = 10 s */

/*==============================================================================
 * API
 *============================================================================*/

/* 初始化裁决器（freertos.c 里在创建任务之前调用一次） */
void M5_WdgInit(void);

/**
 * @brief 每秒裁决一次：全齐才喂 IWDG
 * 由 m4_mon 任务每 1 s 调用。缺位则拒喂 → 最多 2~4 s 后 IWDG 复位。
 */
void M5_WdgKick(void);

/**
 * @brief 申请一段"预期会卡住"的宽限（擦写 Flash、OTA 搬运等）
 * @param hold_ms 宽限时长。⚠️ 必须【小于 IWDG 超时】，否则失去意义。
 *
 * 只用于"明确的、有界的"操作（HAL_FLASHEx_Erase 之类）。
 * ⚠️ 绝不能用来掩盖未知的卡顿 —— 那就等于把看门狗关了。
 */
void M5_WdgHold(uint32_t hold_ms);

/* 查询当前是否在 hold 宽限中（调试用） */
int  M5_WdgIsHolding(void);

#endif /* __M5_WDG_H */
