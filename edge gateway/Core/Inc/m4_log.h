/*==============================================================================
 * M4 · 日志子系统（环形缓冲 + 独立发送任务）
 *
 * 解决的问题（BUG-039）：
 *   原来的 fputc 直接 HAL_UART_Transmit 轮询发送，没有任何保护。
 *   两个任务同时 printf 会互相插队 → 丢行、错序（M1 实测时
 *   "[echo] listening on port 5000" 整行丢失就是这个原因）。
 *   而且轮询发送一行要 3~4ms，高优先级任务被它拖住 → 系统抖动。
 *
 * 三种方案的取舍：
 *   ① 关中断：一行 3ms 全关中断，ISR 全被堵，CAN/串口必丢数据   ✗
 *   ② 互斥量：能保序，但持锁做慢发送违反"锁内不做慢操作"        △
 *   ③ 环形缓冲 + 发送任务（本文件）                            ✓
 *
 * 核心思想：把"慢的串口发送"从调用者的栈和时间线上摘出去。
 *   fputc 只做 memcpy 级别的工作（微秒级），剩下的交给一个低优先级任务慢慢发。
 *============================================================================*/

#ifndef __M4_LOG_H
#define __M4_LOG_H

#include <stdint.h>

/* 环形缓冲大小。1024 字节 ≈ 25 行日志，够吸收 3~4ms 的突发。
   ⚠️ 这是 .bss 静态数组，不走 FreeRTOS heap（heap 只剩 12KB，不能再挤）。 */
#ifndef M4_LOG_BUF_SIZE
#define M4_LOG_BUF_SIZE   1024u
#endif

/* 发送任务参数 */
#define M4_LOG_TASK_STACK   512u
#define M4_LOG_POLL_MS      5u      /* 没数据时让出 CPU 的时间 */
#define M4_LOG_CHUNK        96u     /* 一次最多取这么多字节去发 */

/*==============================================================================
 * API
 *============================================================================*/

/**
 * @brief 启动日志发送任务（在 freertos.c 的 RTOS_THREADS 里调用一次）
 *
 * ⚠️ 在 M4_LogStart() 之前 printf 仍然可用 —— 会走"直接阻塞发送"兜底路径，
 *    只是没有缓冲保护。所以启动顺序上，M4_LogStart() 应尽量靠前。
 */
void M4_LogStart(void);

/**
 * @brief 往日志缓冲里塞一个字符（fputc 会调它）
 *
 * 特性：
 *   - 缓冲满 → 丢弃该字符并计数（日志可以丢，系统不能卡）
 *   - 调度器未启动 → 直接阻塞发送（此时不能用临界区）
 *   - 不用互斥量，只用极短的临界区保护写指针
 */
void M4_LogPutc(char c);

/* 返回累计因缓冲满而丢弃的字符数（监控任务打印用） */
uint32_t M4_LogDropped(void);

/* 返回 1 = 发送任务已就绪（缓冲路径生效） */
int M4_LogReady(void);

#endif /* __M4_LOG_H */
