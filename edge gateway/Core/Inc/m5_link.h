/*==============================================================================
 * M5 · 链路冗余抽象层（以太网主 / ESP8266 备）
 *
 * ⭐ 核心思想：业务代码只认"链路接口"，不认"是以太网还是 WiFi"。
 *    切换时只是换了一个函数指针 —— 不用改一行业务逻辑。
 *
 * 三态 + 滞回：
 *
 *     主链路连续失败 N=3 次          主链路连续成功 M=5 次
 *   PRIMARY ─────────────────────→ BACKUP ─────────────────────→ PRIMARY
 *      │                              │
 *      └────────── 两条都不可用 ──────┘
 *                    ↓
 *               DEGRADED（缓存 / 计数，等恢复）
 *
 * ⚠️ M(5) > N(3) 是【滞回】，这条最容易漏：
 *    如果 M == N，主链路质量在阈值附近波动时系统会每隔 9 s 切一次，
 *    而切换本身又制造更多失败 → 切换振荡。这是现场设备最常见的奇葩故障。
 *
 * ⚠️ 备份链路带宽比主链路低 3 个数量级（ETH 100Mbps vs ESP 几十 KB/s），
 *    所以切到备份必须【降级】：上报周期 3 s → 30 s。
 *============================================================================*/

#ifndef __M5_LINK_H
#define __M5_LINK_H

#include <stdint.h>

typedef enum {
    M5_LINK_PRIMARY  = 0,   /* 以太网 */
    M5_LINK_BACKUP   = 1,   /* ESP8266 */
    M5_LINK_DEGRADED = 2    /* 两条都不可用 */
} m5_link_id_t;

/* 滞回参数 */
/* ⭐ 启动宽限：上电后这段时间内【不裁决切换】（BUG-060）。
   为什么必须有：以太网 PHY 要 1~3 s 才 link up，ESP8266 连 WiFi 更久（好几秒）。
   没有宽限的话，上电瞬间两条链路都是"不可用"，链路层会立刻演一遍
       PRIMARY -> BACKUP -> DEGRADED -> PRIMARY
   日志里看着像"系统刚起来就断网了"，实际只是外设还没就位。
   注意：宽限期内 ESP 状态机照常 tick（让它趁这段时间把链路建好），
   只是不做"切换/告警"这个决策。 */
#define M5_LINK_GRACE_MS    15000u

#define M5_LINK_FAIL_N      3u      /* 主链路连续失败 3 次（3s×3=9s）→ 切备份 */
#define M5_LINK_OK_M        5u      /* 主链路连续成功 5 次（15s）→ 切回主 */

/* 上报周期（降级策略的落点） */
#define M5_REPORT_MS_PRIMARY   3000u
#define M5_REPORT_MS_BACKUP   30000u   /* ⚠️ 备份链路慢，拉长 10 倍 */

/*==============================================================================
 * API
 *============================================================================*/

/* 初始化（在建任务之前调用） */
void M5_LinkInit(void);

/* 由 defaultTask 每 200 ms 驱动一次：跑 ESP 状态机 + 链路切换裁决 */
void M5_LinkTick(uint32_t period_ms);

/* 当前使用哪条链路 */
m5_link_id_t M5_LinkCurrent(void);

/* 当前应该用的上报周期（业务层据此休眠，实现降级） */
uint32_t M5_LinkReportInterval(void);

/**
 * @brief 业务层唯一的发送入口
 * @return 0 = 发送成功；<0 = 失败（业务层据此调 M5_LinkReportResult(0)）
 */
int  M5_LinkSend(const uint8_t *data, uint16_t len);

/* 业务层报告本次上发结果（ok=1 成功）。内部做滞回计数与状态迁移。 */
void M5_LinkReportResult(int ok);

/* 主链路（ETH）的发送实现由 m1_net 注册进来 —— 这样 m5_link 不必
   知道 netconn 的存在，conn 断开时注册方自己返回失败即可。 */
void M5_LinkRegisterEthSend(int (*send)(const uint8_t *data, uint16_t len));

/*==============================================================================
 * ⭐ 全局单调上行序号（切换/重连都不重置）
 *
 * 为什么必须有：切换瞬间可能出现"主链路发了 seq=100 但 ACK 丢了 → 切备份 →
 * 备份重发 seq=100"。上位机按 seq 去重，收到 seq <= last_seq 的直接丢弃，
 * 于是【重复无害、缺失可补】。
 *
 * ⚠️ 若 seq 每次重连都从 0 开始，上位机的去重逻辑会把正常的连续数据全丢掉，
 *    表现为"上报看起来在发，但上位机一条都收不到"（BUG-041 的教训在 M5 爆发）。
 *============================================================================*/
uint32_t M5_UpSeqPeek(void);      /* 取当前序号（打包用） */
void     M5_UpSeqCommit(int ok);  /* ⭐ 只有发送成功才 ++ */

/* 诊断：链路切换次数 / DEGRADED 期间丢失条数 */
uint32_t M5_LinkSwitchCount(void);
uint32_t M5_LinkLostCount(void);

#endif /* __M5_LINK_H */
