/**
  * @brief This function handles Window watchdog interrupt.
  *
  * ⚠️ M5 手写：CubeMX【不会】生成 WWDG_IRQHandler —— 它只生成初始化代码，
  *    中断服务函数要自己补。少了这个函数，EWI 中断进不来（或者链接报未定义），
  *    WWDG 就永远在 ~50 ms 时把板子复位掉。
  */
void WWDG_IRQHandler(void)
{
  /* USER CODE BEGIN WWDG_IRQn 0 */
  extern WWDG_HandleTypeDef hwwdg;   /* wwdg.c 里定义的句柄（本文件没 include wwdg.h） */
  HAL_WWDG_IRQHandler(&hwwdg);       /* 内部清 EWI 标志 + 调 EarlyWakeupCallback */
  /* USER CODE END WWDG_IRQn 0 */
}

